#!/usr/bin/env python3
"""九九の歌：オリジナルのメロディを作って VOICEVOX に歌わせる

使い方（VOICEVOX ENGINE を 127.0.0.1:50021 で起動しておく）:
  python3 kuku_sing.py <出力フォルダ> <段（例 2 または 1-9）> <歌い手ID,…>

- テンポ 112、コード C-Am-F-G（アプリの BGM と同じ）
- 1つの段 = 「◯のだん」1小節 + 九九9行（1行1小節）＝ 10小節
- 先頭に 1小節の休み（アプリ側で 1小節手前から再生して 拍を合わせる）
- 出力: sing_<段>_<歌い手ID>.wav
- メロディは このファイルで作ったオリジナル
"""
import json
import os
import sys
import urllib.request

HOST = "http://127.0.0.1:50021"
TEACHER = 6000            # 歌い方のお手本（波音リツ 歌唱）
BPM = 112
FPS = 24000 / 256         # VOICEVOX のフレームレート
S16 = 60 / BPM / 4        # 16分音符の長さ（秒）

KUKU = {
 1:[("いんいちが","いち"),("いんにが","に"),("いんさんが","さん"),("いんしが","し"),("いんごが","ご"),("いんろくが","ろく"),("いんしちが","しち"),("いんはちが","はち"),("いんくが","く")],
 2:[("にいちが","に"),("ににんが","し"),("にさんが","ろく"),("にしが","はち"),("にご","じゅう"),("にろく","じゅうに"),("にしち","じゅうし"),("にはち","じゅうろく"),("にく","じゅうはち")],
 3:[("さんいちが","さん"),("さんにが","ろく"),("さざんが","く"),("さんし","じゅうに"),("さんご","じゅうご"),("さぶろく","じゅうはち"),("さんしち","にじゅういち"),("さんぱ","にじゅうし"),("さんく","にじゅうしち")],
 4:[("しいちが","し"),("しにが","はち"),("しさん","じゅうに"),("しし","じゅうろく"),("しご","にじゅう"),("しろく","にじゅうし"),("ししち","にじゅうはち"),("しは","さんじゅうに"),("しく","さんじゅうろく")],
 5:[("ごいちが","ご"),("ごに","じゅう"),("ごさん","じゅうご"),("ごし","にじゅう"),("ごご","にじゅうご"),("ごろく","さんじゅう"),("ごしち","さんじゅうご"),("ごは","しじゅう"),("ごっく","しじゅうご")],
 6:[("ろくいちが","ろく"),("ろくに","じゅうに"),("ろくさん","じゅうはち"),("ろくし","にじゅうし"),("ろくご","さんじゅう"),("ろくろく","さんじゅうろく"),("ろくしち","しじゅうに"),("ろくは","しじゅうはち"),("ろっく","ごじゅうし")],
 7:[("しちいちが","しち"),("しちに","じゅうし"),("しちさん","にじゅういち"),("しちし","にじゅうはち"),("しちご","さんじゅうご"),("しちろく","しじゅうに"),("しちしち","しじゅうく"),("しちは","ごじゅうろく"),("しちく","ろくじゅうさん")],
 8:[("はちいちが","はち"),("はちに","じゅうろく"),("はちさん","にじゅうし"),("はちし","さんじゅうに"),("はちご","しじゅう"),("はちろく","しじゅうはち"),("はちしち","ごじゅうろく"),("はっぱ","ろくじゅうし"),("はっく","しちじゅうに")],
 9:[("くいちが","く"),("くに","じゅうはち"),("くさん","にじゅうしち"),("くし","さんじゅうろく"),("くご","しじゅうご"),("くろく","ごじゅうし"),("くしち","ろくじゅうさん"),("くは","しちじゅうに"),("くく","はちじゅういち")],
}
DAN_NAME = {1:"いちのだん",2:"にのだん",3:"さんのだん",4:"よんのだん",5:"ごのだん",
            6:"ろくのだん",7:"ななのだん",8:"はちのだん",9:"きゅうのだん"}

SMALL = set("ゃゅょぁぃぅぇぉ")
def morae(s):
    out = []
    for ch in s.replace(" ", ""):
        if ch in SMALL and out:
            out[-1] += ch
        else:
            out.append(ch)
    return out

# リズム（16分音符いくつ分か）。かけ声は前半2拍、こたえは後半2拍（最後に少し休み）
CALL_R = {1:[8], 2:[4,4], 3:[2,2,4], 4:[2,2,2,2], 5:[2,1,1,2,2], 6:[1,1,2,1,1,2]}
ANS_R  = {1:[6], 2:[2,4], 3:[2,2,2], 4:[1,1,2,2], 5:[1,1,1,1,2], 6:[1,1,1,1,1,1]}
HEAD_R = {4:[2,2,2,6], 5:[2,2,2,2,4]}

# コードごとのメロディ（かけ声 / こたえ / こたえの最後の音）— C-Am-F-G
MEL = {
 "C":  ([67,67,72,69,67,67], [64,67,64,62,64,62], 60),
 "Am": ([69,69,72,72,69,69], [72,69,67,69,67,69], 64),
 "F":  ([65,65,69,69,72,69], [72,69,65,67,65,67], 65),
 "G":  ([67,67,71,71,74,71], [74,71,67,69,67,69], 67),
}
CHORDS = ["C", "Am", "F", "G"]


def build_score(dan):
    """(音の高さ or None, 16分音符の数, 歌詞) の列 と 各行の開始小節"""
    ev = [(None, 16, "")]                      # 1小節 休み
    # 1小節目：「◯のだん」（C）
    hm = morae(DAN_NAME[dan])
    hp = [60, 64, 67, 69, 72][-len(hm):] if len(hm) <= 5 else [67] * len(hm)
    hr = HEAD_R[len(hm)]
    ev += [(p, r, m) for p, r, m in zip(hp, hr, hm)]
    # 2小節目から 九九
    for i, (call, ans) in enumerate(KUKU[dan]):
        ch = CHORDS[(i + 1) % 4]
        cm, am = morae(call), morae(ans)
        ct, at, fin = MEL[ch]
        cp = ct[:len(cm)]
        ap = at[:len(am) - 1] + [fin]
        ev += [(p, r, m) for p, r, m in zip(cp, CALL_R[len(cm)], cm)]
        ev += [(p, r, m) for p, r, m in zip(ap, ANS_R[len(am)], am)]
        rest = 8 - sum(ANS_R[len(am)])
        if rest:
            ev.append((None, rest, ""))
    ev.append((None, 8, ""))                   # おわりに 少し休み
    # 16分音符 → フレーム（絶対時刻から丸めて ずれをためない）
    notes, pos = [], 0
    for p, r, m in ev:
        f0 = round(pos * S16 * FPS); pos += r; f1 = round(pos * S16 * FPS)
        notes.append({"key": p, "frame_length": f1 - f0, "lyric": m})
    return {"notes": notes}


def post(path, body):
    req = urllib.request.Request(HOST + path, data=json.dumps(body).encode(),
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=170) as r:
        return r.read()


def main():
    out, dans, singers = sys.argv[1], sys.argv[2], [int(x) for x in sys.argv[3].split(",")]
    a, _, b = dans.partition("-")
    os.makedirs(out, exist_ok=True)
    for dan in range(int(a), int(b or a) + 1):
        score = build_score(dan)
        q = json.loads(post(f"/sing_frame_audio_query?speaker={TEACHER}", score))
        for sp in singers:
            wav = post(f"/frame_synthesis?speaker={sp}", q)
            fn = os.path.join(out, f"sing_{dan}_{sp}.wav")
            open(fn, "wb").write(wav)
            print("ok", fn, len(wav))


if __name__ == "__main__":
    main()
